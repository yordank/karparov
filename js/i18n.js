(function () {
  const root = document.documentElement;
  const langToggle = document.getElementById('langToggle');

  function resolve(dict, key) {
    return key.split('.').reduce((obj, part) => (obj && obj[part] !== undefined ? obj[part] : undefined), dict);
  }

  function applyLang(lang) {
    const dict = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const value = resolve(dict, el.getAttribute('data-i18n'));
      if (value !== undefined) el.innerHTML = value;
    });
    root.lang = lang;
    langToggle.textContent = lang === 'en' ? 'BG' : 'EN';
    langToggle.setAttribute('aria-label', lang === 'en' ? 'Switch to Bulgarian' : 'Превключи на английски');
    document.title = lang === 'bg' ? translations.bg.hero.name : translations.en.hero.name;
    try { localStorage.setItem('lang', lang); } catch (e) {}
  }

  let saved = 'en';
  try { saved = localStorage.getItem('lang') || 'en'; } catch (e) {}
  applyLang(saved);

  langToggle.addEventListener('click', () => {
    applyLang(root.lang === 'en' ? 'bg' : 'en');
  });
})();
